// users collection: one document per user.
// Works for Firestore and MongoDB. Dates are JS Date objects in app code;
// each driver converts them (BSON Date in MongoDB, Timestamp in Firestore).

export type AuthProvider = "google" | "email" | "github"; // "email" = email + password

export interface Identity {
  provider: AuthProvider;
  provider_uid: string; // with Firebase Auth, the Firebase uid
  created_at: Date;
  updated_at: Date;
}

export interface UserProfile {
  dob?: string;    // "YYYY-MM-DD"
  gender?: string;
  created_at: Date;
  updated_at: Date;
}

export type Theme = "light" | "dark" | "system";

export interface UserSettings {
  schema_version: number;
  theme?: Theme;
  language?: string;  // BCP 47, e.g. "en", "hi-IN"
  timezone?: string;  // IANA, e.g. "Asia/Kolkata"
  notifications?: {
    email?: boolean;
    push?: boolean;
  };
  created_at: Date;
  updated_at: Date;
}

export interface User {
  _id: string;             // UUID v4, generated by the app
  display_name: string;
  email?: string;          // lowercase; unique when present
  avatar_url?: string;
  identities: Identity[];  // 1 or more
  profile?: UserProfile;   // 0 or 1
  settings?: UserSettings; // 0 or 1
  created_at: Date;
  updated_at: Date;
}
